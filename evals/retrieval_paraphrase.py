"""A second question set for the retrieval benchmark, written by an LLM rather than by the author.

The gold questions were written by someone who had read the regulations, so they may echo its wording.
Each is rewritten here by a free-tier model that sees only the question (never the regulation text),
the way a passenger might say it on the phone; the relevant passages are carried over unchanged.

uv run python -m evals.retrieval_paraphrase   # -> evals/retrieval_paraphrase.yaml (once; --force to redo)
"""

from __future__ import annotations

import argparse
import asyncio
from pathlib import Path

import yaml

from evals.retrieval import GOLD
from vocalis.llm.router import LLMRouter

OUT = Path("evals/retrieval_paraphrase.yaml")
MODELS = ["cerebras/qwen-3.8-27b", "gemini/gemini-flash-lite-latest"]  # not the retriever under test
PROMPT = """Rewrite this question the way a stressed passenger would ask it on the phone, in your own words.
Keep any airline, airport, country and number in it; do not add facts; avoid the original's key phrases
where a natural alternative exists. Reply with the rewritten question only.

Question: {q}"""


async def main_async(force: bool) -> None:
    if OUT.exists() and not force:
        print(f"{OUT} exists; pass --force to regenerate")
        return
    gold = yaml.safe_load(GOLD.read_text(encoding="utf-8"))
    router = LLMRouter()
    out = []
    models: set[str] = set()
    for g in gold:
        for attempt in range(5):  # free tiers rate-limit in bursts: back off and retry
            try:
                r = await router.complete(
                    MODELS,
                    [{"role": "user", "content": PROMPT.format(q=g["q"])}],
                    temperature=0.7,
                    max_tokens=1500,
                    tags={"role": "retrieval_paraphrase"},
                )
                break
            except RuntimeError:
                await asyncio.sleep(20 * (attempt + 1))
        else:
            raise RuntimeError(f"no model could paraphrase: {g['q']}")
        models.add(r.model)
        out.append({"q": r.text.strip().strip('"'), "relevant": g["relevant"], "from": g["q"]})
    header = (
        "# Generated by evals/retrieval_paraphrase.py: each gold question rewritten by "
        f"{', '.join(sorted(models))} without the regulation text; relevant passages carried over.\n"
    )
    OUT.write_text(
        header + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8"
    )
    print(f"{len(out)} paraphrases -> {OUT}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    asyncio.run(main_async(ap.parse_args().force))


if __name__ == "__main__":
    main()
